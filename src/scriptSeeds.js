/** Додає стартові папки й скрипти, яких ще немає і які не були видалені;
 *  оновлює стартові тексти, якщо їх не редагували. */
export function addMissingSeeds(s) {
  const del = s.deleted || {};
  for (const f of SEED_FOLDERS) if (!del[f.id] && !s.scriptFolders.some((x) => x.id === f.id)) s.scriptFolders.push({ ...f });
  for (const f of s.scriptFolders) if (f.parentId == null) f.parentId = '';
  for (const sc of [...SEED_SCRIPTS, ...CAFE_SCRIPTS]) {
    if (del[sc.id]) continue;
    const ex = s.scripts.find((x) => x.id === sc.id);
    if (!ex) s.scripts.push({ ...sc });
    else if ((OLD_TEXTS[sc.id] || []).includes(ex.text)) ex.text = sc.text;
  }
  return s;
}
